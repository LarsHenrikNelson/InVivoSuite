"""2D variant of the kernel Current Source Density method for planar
electrode arrays (also usable for any 2D geometry, e.g. staggered shanks).

Ported from Elephant (``current_source_density_src/KCSD.py``, BSD-3-Clause)
by Chaitanya Chintaluri, following Potworowski et al. 2012.

Note: for single-shank (strictly 1D) probes KCSD1D is the appropriate and
better-conditioned variant. KCSD2D requires distinct y values across
electrodes.
"""

import numpy as np
from scipy import integrate
from scipy.spatial import distance

from .basis import basis_2D
from .kcsd import KCSD
from .utils import distribute_srcs_2D

__all__ = ["KCSD2D"]


class KCSD2D(KCSD):
    """KCSD2D - kCSD for 2D electrode configurations.

    Parameters
    ----------
    ele_pos : np.ndarray, (n_ele, 2)
        Electrode (x, y) positions in a consistent length unit (e.g. um).
    pots : np.ndarray, (n_ele, n_time)
        Measured potentials.
    src_type : {'gauss', 'step', 'gauss_lim'}
        Basis function type. Default 'gauss'.
    sigma : float
        Conductivity. Default 1.0.
    h : float
        Slice thickness. Default 1.0.
    n_src_init : int
        Requested number of basis sources. Default 1000.
    R_init : float
        Initial basis radius in ele_pos units. Default 0.23.
    lambd : float
        Tikhonov regularization. Default 0.0.
    xmin, xmax, ymin, ymax, ext_x, ext_y, gdx, gdy : float
        Estimation window, extensions beyond the electrode plane, and
        estimation grid steps. Defaults: electrode extent, no extension,
        1% of the extent per axis.
    """

    def __init__(self, ele_pos, pots, **kwargs):
        ele_pos = np.asarray(ele_pos, dtype=float)
        if ele_pos.ndim != 2 or ele_pos.shape[1] != 2:
            raise ValueError("ele_pos for KCSD2D must be (n_ele, 2)")
        if kwargs.get("ymin") is None and ele_pos.shape[0] > 1:
            if np.min(ele_pos[:, 1]) == np.max(ele_pos[:, 1]):
                raise ValueError(
                    "KCSD2D requires distinct y coordinates. For single-shank "
                    "(laminar) probes use KCSD1D."
                )
        super().__init__(ele_pos, pots, **kwargs)

    def estimate_at(self):
        """Locations at which the estimation is wanted.

        Defines ``estm_x``, ``estm_y`` grids, ``ngx``, ``ngy``, ``n_estm``.
        NOTE: the number of grid steps per axis is rounded to the nearest
        integer before building the grid (Elephant's raw-float complex step
        into ``np.mgrid`` silently truncates near-integer values).
        """
        nx = int(np.round((self.xmax - self.xmin) / self.gdx))
        ny = int(np.round((self.ymax - self.ymin) / self.gdy))
        self.estm_x, self.estm_y = np.mgrid[
            self.xmin : self.xmax : complex(0, nx),
            self.ymin : self.ymax : complex(0, ny),
        ]
        self.n_estm = self.estm_x.size
        self.ngx, self.ngy = self.estm_x.shape

    def place_basis(self):
        """Places basis sources of the requested type; defines ``basis``,
        ``R``, ``src_x``, ``src_y``, ``n_src``."""
        try:
            self.basis = basis_2D[self.src_type]
        except KeyError as exc:
            raise KeyError(
                "Invalid source_type for basis! available are:",
                list(basis_2D.keys()),
            ) from exc
        self.src_x, self.src_y, self.R = distribute_srcs_2D(
            self.estm_x,
            self.estm_y,
            self.n_src_init,
            self.ext_x,
            self.ext_y,
            self.R_init,
        )
        self.n_src = self.src_x.size

    def create_src_dist_tables(self):
        """Distance tables between sources, electrodes and estimation points;
        defines ``src_ele_dists`` (n_src, n_ele), ``src_estm_dists``
        (n_src, n_estm) and ``dist_max``."""
        src_loc = np.array((self.src_x.ravel(), self.src_y.ravel()))
        est_loc = np.array((self.estm_x.ravel(), self.estm_y.ravel()))
        self.src_ele_dists = distance.cdist(src_loc.T, self.ele_pos, "euclidean")
        self.src_estm_dists = distance.cdist(src_loc.T, est_loc.T, "euclidean")
        self.dist_max = (
            max(np.max(self.src_ele_dists), np.max(self.src_estm_dists)) + self.R
        )

    def estm_points(self):
        """Flat estimation grid coordinates (n_estm, 2)."""
        return np.column_stack(
            (self.estm_x.ravel(), self.estm_y.ravel())
        )

    def forward_model(self, x, R, h, sigma, src_type):
        """Potential at (x, 0) generated by a basis source at the origin;
        Eq. 22 kCSD, Jan 2012."""
        pot, _ = integrate.dblquad(
            self.int_pot_2D,
            -R,
            R,
            lambda x: -R,
            lambda x: R,
            args=(x, R, h, src_type),
        )
        pot *= 1.0 / (2.0 * np.pi * sigma)  # Potential basis functions
        return pot

    def int_pot_2D(self, xp, yp, x, R, h, basis_func):
        """FWD model core: contribution of point (xp, yp) to the potential
        at (x, 0)."""
        y = ((x - xp) ** 2 + yp**2) ** 0.5
        if y < 0.00001:
            y = 0.00001
        dist = np.sqrt(xp**2 + yp**2)
        return np.arcsinh(h / y) * basis_func(dist, R)
