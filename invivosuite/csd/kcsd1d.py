"""1D variant of the kernel Current Source Density method for laminar
(single-shank) probes.

Ported from Elephant (``current_source_density_src/KCSD.py``, BSD-3-Clause)
by Chaitanya Chintaluri and Michal Czerwinski, following Potworowski et al.
2012.
"""

import numpy as np
from scipy import integrate
from scipy.spatial import distance

from .basis import basis_1D
from .kcsd import KCSD
from .utils import distribute_srcs_1D

__all__ = ["KCSD1D"]


class KCSD1D(KCSD):
    """KCSD1D - kCSD for 1D (laminar) electrode configurations.

    Parameters
    ----------
    ele_pos : np.ndarray, (n_ele, 1) or (n_ele,)
        Electrode depths in a consistent length unit (e.g. um).
    pots : np.ndarray, (n_ele, n_time)
        Measured potentials.
    src_type : {'gauss', 'step', 'gauss_lim'}
        Basis function type. Default 'gauss'.
    sigma : float
        Conductivity. Default 1.0.
    h : float
        Slice thickness. Default 1.0.
    n_src_init : int
        Requested number of basis sources (Elephant default 1000; the 1D
        variant historically used 300).
    R_init : float
        Initial basis radius in ele_pos units. Default 0.23.
    lambd : float
        Tikhonov regularization. Default 0.0.
    xmin, xmax, ext_x, gdx : float
        Estimation window along depth, extension beyond electrodes, and
        estimation grid step. Defaults: electrode extent, no extension, 1%
        of the extent.
    """

    def __init__(self, ele_pos, pots, **kwargs):
        ele_pos = np.asarray(ele_pos, dtype=float)
        if ele_pos.ndim == 1:
            ele_pos = ele_pos[:, np.newaxis]
        super().__init__(ele_pos, pots, **kwargs)

    def estimate_at(self):
        """Locations at which the estimation is wanted.

        Defines ``estm_x`` (n_estm,) and ``ngx``. NOTE: the number of grid
        steps is rounded to the nearest integer before building the grid;
        Elephant passes the raw float into ``np.mgrid``, which silently
        truncates near-integer floats (e.g. 0.9/0.02 -> 44 instead of 45
        points).
        """
        nx = int(np.round((self.xmax - self.xmin) / self.gdx))
        self.estm_x = np.mgrid[self.xmin : self.xmax : complex(0, nx)]
        self.n_estm = self.estm_x.size
        self.ngx = self.estm_x.shape[0]

    def place_basis(self):
        """Places basis sources of the requested type; defines ``basis``,
        ``R``, ``src_x``, ``n_src``."""
        try:
            self.basis = basis_1D[self.src_type]
        except KeyError as exc:
            raise KeyError(
                "Invalid source_type for basis! available are:",
                list(basis_1D.keys()),
            ) from exc
        self.src_x, self.R = distribute_srcs_1D(
            self.estm_x, self.n_src_init, self.ext_x, self.R_init
        )
        self.n_src = self.src_x.size

    def create_src_dist_tables(self):
        """Distance tables between sources, electrodes and estimation points;
        defines ``src_ele_dists`` (n_src, n_ele), ``src_estm_dists``
        (n_src, n_estm) and ``dist_max``."""
        src_loc = self.src_x.ravel().reshape((-1, 1))
        est_loc = self.estm_x.ravel().reshape((-1, 1))
        self.src_ele_dists = distance.cdist(src_loc, self.ele_pos, "euclidean")
        self.src_estm_dists = distance.cdist(src_loc, est_loc, "euclidean")
        self.dist_max = (
            max(np.max(self.src_ele_dists), np.max(self.src_estm_dists)) + self.R
        )

    def estm_points(self):
        """Flat estimation grid coordinates (n_estm, 1)."""
        return self.estm_x.ravel().reshape((-1, 1))

    def forward_model(self, x, R, h, sigma, src_type):
        """Potential at (x, 0) generated by a basis source at the origin;
        Eq. 26 kCSD, Jan 2012."""
        pot, _ = integrate.quad(
            self.int_pot_1D, -R, R, args=(x, R, h, src_type)
        )
        pot *= 1.0 / (2.0 * sigma)
        return pot

    def int_pot_1D(self, xp, x, R, h, basis_func):
        """FWD model core: contribution of point xp to the potential at x."""
        m = np.sqrt((x - xp) ** 2 + h**2) - abs(x - xp)
        m *= basis_func(abs(xp), R)  # xp is the distance
        return m
